// Incident report (.docx), built entirely in the browser. This module is loaded on demand (dynamic import)
// so the docx library never weighs on page load. It takes display-ready text only: callers resolve every
// internal id (contractor, camera, asset) to a name before passing it in.

import {
  AlignmentType,
  BorderStyle,
  Document,
  Footer,
  HeadingLevel,
  ImageRun,
  Packer,
  Paragraph,
  Table,
  TableCell,
  TableRow,
  TextRun,
  VerticalAlign,
  WidthType,
} from 'docx';

export type ReportImage = { data: ArrayBuffer; type: 'jpg' | 'png'; width: number; height: number; caption: string };

export type ReportInput = {
  reportId: string;
  title: string;
  township: string;
  fields: [label: string, value: string][];
  before: ReportImage | { missing: string };
  after: ReportImage | { missing: string };
  generatedAt: string;
};

const NAVY = '0B1846';
const MUTED = '4A5372';
const LINE = 'DFE3EC';
// A4 with 2 cm margins leaves about 17 cm of text width; each evidence cell gets just under half of it.
const PAGE_MARGIN_TWIP = 1134;
const CELL_WIDTH_TWIP = 4800;
const IMAGE_MAX_W = 300; // px (docx converts at 96 dpi), fits the cell with padding
const IMAGE_MAX_H = 225;

const NOT_PROVIDED = 'Not provided';
const thin = { style: BorderStyle.SINGLE, size: 4, color: LINE };
const borders = { top: thin, bottom: thin, left: thin, right: thin, insideHorizontal: thin, insideVertical: thin };

const text = (value: string, opts: { bold?: boolean; color?: string; size?: number; italics?: boolean } = {}) =>
  new TextRun({ text: value, font: 'Calibri', size: opts.size ?? 20, bold: opts.bold, italics: opts.italics, color: opts.color ?? NAVY });

function fit(w: number, h: number) {
  const scale = Math.min(IMAGE_MAX_W / w, IMAGE_MAX_H / h, 1);
  return { width: Math.round(w * scale), height: Math.round(h * scale) };
}

function evidenceCell(label: string, image: ReportImage | { missing: string }) {
  const children: Paragraph[] = [new Paragraph({ spacing: { after: 80 }, children: [text(label, { bold: true })] })];
  if ('data' in image) {
    children.push(
      new Paragraph({
        alignment: AlignmentType.CENTER,
        children: [
          new ImageRun({
            type: image.type,
            data: image.data,
            transformation: fit(image.width, image.height),
            altText: { name: label, description: image.caption, title: label },
          }),
        ],
      }),
      new Paragraph({ spacing: { before: 80 }, children: [text(image.caption, { size: 16, color: MUTED })] })
    );
  } else {
    children.push(
      new Paragraph({ spacing: { before: 400, after: 80 }, alignment: AlignmentType.CENTER, children: [text(NOT_PROVIDED, { bold: true, color: MUTED })] }),
      new Paragraph({ spacing: { after: 400 }, alignment: AlignmentType.CENTER, children: [text(image.missing, { size: 16, color: MUTED })] })
    );
  }
  return new TableCell({
    width: { size: CELL_WIDTH_TWIP, type: WidthType.DXA },
    margins: { top: 120, bottom: 120, left: 120, right: 120 },
    verticalAlign: VerticalAlign.TOP,
    children,
  });
}

export async function buildReport(input: ReportInput): Promise<Blob> {
  const facts = new Table({
    width: { size: 2 * CELL_WIDTH_TWIP, type: WidthType.DXA },
    columnWidths: [2600, 2 * CELL_WIDTH_TWIP - 2600],
    borders,
    rows: input.fields.map(
      ([label, value]) =>
        new TableRow({
          cantSplit: true,
          children: [
            new TableCell({
              shading: { fill: 'EEF1F6' },
              margins: { top: 60, bottom: 60, left: 120, right: 120 },
              children: [new Paragraph({ children: [text(label, { bold: true })] })],
            }),
            new TableCell({
              margins: { top: 60, bottom: 60, left: 120, right: 120 },
              children: (value || NOT_PROVIDED).split('\n').map(line => new Paragraph({ children: [text(line)] })),
            }),
          ],
        })
    ),
  });

  const evidence = new Table({
    width: { size: 2 * CELL_WIDTH_TWIP, type: WidthType.DXA },
    columnWidths: [CELL_WIDTH_TWIP, CELL_WIDTH_TWIP],
    borders,
    rows: [new TableRow({ cantSplit: true, children: [evidenceCell('Before', input.before), evidenceCell('After', input.after)] })],
  });

  const doc = new Document({
    creator: 'Orbit',
    title: `${input.title} (${input.reportId})`,
    sections: [
      {
        properties: {
          page: { margin: { top: PAGE_MARGIN_TWIP, bottom: PAGE_MARGIN_TWIP, left: PAGE_MARGIN_TWIP, right: PAGE_MARGIN_TWIP } },
        },
        footers: {
          default: new Footer({
            children: [
              new Paragraph({
                alignment: AlignmentType.CENTER,
                children: [text(`Images anonymised at capture. Generated by Orbit on ${input.generatedAt}.`, { size: 16, color: MUTED })],
              }),
            ],
          }),
        },
        children: [
          new Paragraph({ heading: HeadingLevel.HEADING_1, children: [text(input.title, { bold: true, size: 32 })] }),
          new Paragraph({ spacing: { after: 240 }, children: [text(`${input.township} · Incident report ${input.reportId}`, { color: MUTED })] }),
          facts,
          new Paragraph({ heading: HeadingLevel.HEADING_2, spacing: { before: 360, after: 120 }, children: [text('Evidence', { bold: true, size: 26 })] }),
          evidence,
          new Paragraph({
            spacing: { before: 240 },
            children: [
              text(
                'This report is a copy outside the retention policy: the images in it are not deleted automatically. Store it securely and delete it when no longer needed.',
                { size: 16, italics: true, color: MUTED }
              ),
            ],
          }),
        ],
      },
    ],
  });
  return Packer.toBlob(doc);
}
